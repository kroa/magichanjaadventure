/**
 * 글자마다의 **부수(部首)와 부수를 뺀 획수.**
 *
 * ── 왜 여기 있나 ────────────────────────────────────────────────────
 * 부수는 한자 사전이라면 당연히 있어야 하는 값인데 우리 시드에는 아예 없었다.
 * 낱말 페이지가 얇았던 것도 한몫은 여기에 있다 — 글자 카드에 훈·음·급수·총획밖에
 * 적을 것이 없었다.
 *
 * 시드 튜플에 열을 더하지 않은 이유: 부수는 **사전에만 필요하다.** 게임은 쓰지 않는다.
 * 시드를 건드리면 D1 스키마·마이그레이션·1,028행 SQL 이 전부 따라 움직인다.
 * `official-grades.ts` 와 같은 방식으로, 사전이 직접 읽는 표로 둔다.
 *
 * ── 값의 출처 ────────────────────────────────────────────────────────
 * 사단법인 한국어문회가 배포하는 배정한자 마스터 파일
 * ("배정한자 전체 대표훈음 부수 음표 명기본(xls).xls", 전 급수 5,978자)의
 * `부수`·`획수` 열에서 그대로 옮겼다. 우리 1028자 가운데 빠진 글자는 없다.
 *
 * `rest` 는 **부수를 뺀 획수**다. 총획은 시드가 갖고 있으므로 옮기지 않았다.
 * 다만 옮기면서 대조해 보니 6자의 총획이 공식과 어긋나 있었고(極·毒·肅·憶·藏·華),
 * 그건 시드 쪽에서 바로잡았다.
 */
