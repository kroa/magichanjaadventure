import { ALL, GRADES } from './index';
import { ALL_WORDS } from './words';
import { DICT_ORIGIN } from '$lib/sites';

/**
 * 사이트맵에 실을 주소 — **한 곳에서 만든다.**
 *
 * XML 과 텍스트 두 형식으로 내보내므로, 목록이 두 군데 있으면 반드시 어긋난다.
 *
 * ── 왜 텍스트 사이트맵도 두는가 ──────────────────────────────────────
 * 구글 서치콘솔이 XML 사이트맵을 이틀째 "가져올 수 없음" 으로 두고 있다.
 * 우리가 잴 수 있는 것은 전부 정상이다 — 200, 올바른 XML, 데이터센터 IP 에서도,
 * Googlebot 을 사칭해도, 열 번 연속으로도. 그래서 원인을 아직 모른다.
 *
 * 구글은 **줄바꿈으로 나눈 주소 목록**도 사이트맵으로 받는다. XML 처리 쪽에
 * 무언가 걸려 있다면 이쪽이 우회로가 되고, 아니어도 잃는 것이 없다.
 * 원인을 모를 때는 길을 하나 더 내 두는 편이 낫다.
 *
 * ── 게임은 싣지 않는다 ───────────────────────────────────────────────
 * 게임은 로그인 뒤에 있어 크롤러가 볼 수 없다. 없는 페이지를 실은 사이트맵은
 * 신뢰만 깎는다.
 */

/*
 * `priority` 와 `changefreq` 는 넣지 않는다.
 *
 * 구글이 **무시한다고 공식 문서에 명시**했다. 넣어 두면 읽는 사람은 그것이
 * 무슨 일을 한다고 믿게 되고, 파일만 커진다. 빼면 파서가 볼 것도 줄어든다.
 *
 * `lastmod` 도 넣지 않는다. 구글은 그 값을 실제 페이지 변경과 대조해
 * "일관되고 검증 가능하게 정확할 때만" 쓴다. 우리 1,845장은 시드에서 나오므로
 * 페이지마다의 실제 변경 시각이 없고, 빌드 시각을 전부 같은 값으로 채우면
 * "1,845장이 동시에 바뀜" 이 되어 정확히 구글이 불신하는 꼴이 된다.
 * 그리고 그 불신은 해당 URL 만이 아니라 **사이트맵 전체의 lastmod 를 통째로** 버린다.
 * 시드에 진짜 개정 이력이 생기면 그때 넣는다.
 */

/**
 * 경로 전체를 한 번에 인코딩한다.
 *
 * 조각마다 `encodeURIComponent` 를 쓰면 `/hanja/급수/8%EA%B8%89` 처럼 한글이 섞여 나온다.
 * 동작은 하지만 사이트맵은 RFC 3986 으로 이스케이프된 주소를 요구하므로 한 모양으로 통일한다.
 */
const at = (path: string) => encodeURI(`${DICT_ORIGIN}${path}`);

export function sitemapEntries(): string[] {
	return [
		at('/hanja'),
		at('/hanja/급수'),
		at('/hanja/낱말'),
		...GRADES.map((g) => at(`/hanja/급수/${g.label}`)),
		...GRADES.map((g) => at(`/hanja/급수/${g.label}/따라쓰기`)),
		...GRADES.map((g) => at(`/hanja/급수/${g.label}/퀴즈`)),
		...ALL.map((e) => at(`/hanja/${e.character}`)),
		...ALL_WORDS.map((w) => at(`/hanja/낱말/${w.word}`))
	];
}
